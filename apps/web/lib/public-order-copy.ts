// Explicit labels avoid ICU locale fallback differences between SSR and browsers.
export function publicWeekday(locale: Locale, day: string) {
  const labels = {
    en: [
      "Monday",
      "Tuesday",
      "Wednesday",
      "Thursday",
      "Friday",
      "Saturday",
      "Sunday",
    ],
    de: [
      "Montag",
      "Dienstag",
      "Mittwoch",
      "Donnerstag",
      "Freitag",
      "Samstag",
      "Sonntag",
    ],
    it: [
      "lunedì",
      "martedì",
      "mercoledì",
      "giovedì",
      "venerdì",
      "sabato",
      "domenica",
    ],
    sq: [
      "e hënë",
      "e martë",
      "e mërkurë",
      "e enjte",
      "e premte",
      "e shtunë",
      "e diel",
    ],
  };
  return (
    labels[locale][
      [
        "MONDAY",
        "TUESDAY",
        "WEDNESDAY",
        "THURSDAY",
        "FRIDAY",
        "SATURDAY",
        "SUNDAY",
      ].indexOf(day)
    ] ?? day
  );
}
