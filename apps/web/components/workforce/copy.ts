export function workforceDateLabel(
  c: WorkforceCopy,
  date: string,
  weekday = true,
) {
  const d = new Date(date + "T12:00:00Z"),
    i = (d.getUTCDay() + 6) % 7;
  return (
    String(d.getUTCDate()) +
    " " +
    (weekday ? c.weekdays.split(",")[i] : c.months.split(",")[d.getUTCMonth()])
  );
}
