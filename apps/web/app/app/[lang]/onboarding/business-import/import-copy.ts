function localized(copy: Copy, locale: PlatformLocale) {
  const labels = names[locale];
  const map = (keys: readonly string[], values: string[]) =>
    Object.fromEntries(keys.map((key, i) => [key, values[i]!])) as Record<
      string,
      string
    >;
  return {
    ...copy,
    days: labels.days,
    profiles: map(businessProfileIds, labels.profiles),
    roles: map(["PRIMARY", "GALLERY", "LOGO", "HERO"], labels.roles),
    stations: map(["KITCHEN", "BAR", "DESSERT"], labels.stations),
    allergens: map(importAllergenCodes, labels.allergens),
  };
}
